#!/usr/bin/env node
// Regenerate src/renderer/src/lib/settingsSearchIndex.ts from the Settings
// page sources. Run after adding or removing a setting; the settings-search
// test fails until you do.
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { PAGE_SOURCES, pageKeys } from './settings-search-sources.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (f) => fs.readFileSync(path.join(root, 'src/renderer/src/components', f), 'utf8')
let out = `// GENERATED by \`npm run gen:settings-search\` from the Settings page sources
// (scripts/settings-search-sources.mjs). test/settings-search.test.ts fails
// when a page renders a key this index does not have — regenerate.

import type { SettingsPage } from '../components/Settings'

export const SETTINGS_SEARCH_KEYS: Record<SettingsPage, readonly string[]> = {
`
const pages = Object.keys(PAGE_SOURCES)
pages.forEach((p, i) => {
  out += `  ${p}: [\n${pageKeys(p, read).map((k) => `    '${k}'`).join(',\n')}\n  ]${i < pages.length - 1 ? ',' : ''}\n`
})
out += '}\n'
fs.writeFileSync(path.join(root, 'src/renderer/src/lib/settingsSearchIndex.ts'), out)
console.log('settingsSearchIndex.ts regenerated')
