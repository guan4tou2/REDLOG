// The bundle README's section on what RedLog adds to a row (Spec 071 FR-097).
// A module of its own so test/bundle-readme-rows.test.ts can check the reading
// rule and the worked examples it states against what the writer and
// restoreDataDepth do: the README is read by a recipient who has only it.

export const ROW_ADDITIONS_README: readonly string[] = [
  '## What RedLog adds to a row',
  '',
  '- **`data._ingest`** — the receiver\'s stamp (rows from older versions',
  '  have none): which door the row came in by (`door`), what produced it',
  '  (`producer`), its `event_id`, and `collapsed` when the row holds',
  '  wrappers (below). It is part of `data`.',
  '',
  '### Values nested more than 64 levels deep',
  '',
  '`data` is stored at most 64 levels deep, `data` itself counting as level',
  '1. Where a container at level 64 holds another container, it is stored',
  'as a wrapper instead: an object whose single key is `_collapsed` and whose',
  'value is a string. The string is the JSON text of the value the sender',
  'sent there, as RedLog serialises it: the spelling of numbers and strings,',
  'whitespace and duplicate keys are not preserved, as for every other part',
  'of `data` (RedLog parses what it receives). `data._ingest.collapsed`',
  'counts the wrappers in the row. For example, sent at level 64,',
  '',
  '```',
  '[ [1.0, "\\u0041", 1e2] ]',
  '{"a": 1, "a": 2, "b": []}',
  '```',
  '',
  'are stored as',
  '',
  '```',
  '{"_collapsed":"[[1,\\"A\\",100]]"}',
  '{"_collapsed":"{\\"a\\":2,\\"b\\":[]}"}',
  '```',
  '',
  'To read a row: at level 64, and only there, replace each object whose',
  'single key is `_collapsed`, with a string value, by what parsing that',
  'string gives. An object of that shape at any other level is the sender\'s',
  'own: leave it as it is. A sender\'s own object of that shape at level 64',
  'is itself wrapped, so at level 64 the rule has no exceptions.',
  '',
  'Each row of `events.jsonl` is hashed into the chain and signed with',
  '`data` as stored, `_ingest` and wrappers included, so the verifier checks',
  'it as it is. Rows of `events_logged.jsonl` carry `_ingest` and wrappers',
  'too, but are not chained or signed one by one: the file is covered as a',
  'whole by its SHA-256 in `manifest.json`, which the seal signs, and',
  '`tiers.loggedDigest` there records the row count and SHA-256 of the',
  'logged tier as RedLog held it at export.',
  ''
]
